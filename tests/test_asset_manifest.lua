local tileData = dofile("data/map_tiles.lua")

local referencedFiles = {}
local logicalTiles = 0

local function validateLevel(level, kind, folder, filenameForCoordinate)
    for coordinate, value in pairs(level[kind] or {}) do
        local plane, atlasX, atlasZ = coordinate:match("^(%d+):(%d+):(%d+)$")
        assert(plane and tonumber(plane) <= 3, "invalid tile coordinate: " .. coordinate)
        local filename = type(value) == "string"
            and value
            or filenameForCoordinate(plane, atlasX, atlasZ)
        assert(filename:match("^[%w_.-]+%.png$") and not filename:find("..", 1, true),
            "tile aliases must be plain PNG filenames without traversal: " .. filename)
        local path = string.format("resources/%s/%s/%s", folder, level.folder, filename)
        local file = assert(io.open(path, "rb"), "missing generated asset: " .. path)
        local header = assert(file:read(24), "truncated generated asset: " .. path)
        file:close()
        assert(header:sub(1, 8) == "\137PNG\r\n\26\n", "asset is not PNG: " .. path)
        local width, height = string.unpack(">I4I4", header, 17)
        assert(width <= 1024 and height <= 1024,
            "asset exceeds the Client API 1024x1024 limit: " .. path)
        referencedFiles[path] = true
        logicalTiles = logicalTiles + 1
    end
end

for _, level in ipairs(tileData.levels) do
    assert(type(level.folder) == "string" and level.span > 0 and level.nativeScale > 0,
        "each generated level requires folder, span, and nativeScale metadata")
    validateLevel(level, "available", "maps", function(plane, atlasX, atlasZ)
        return string.format("%s_%s_%s.png", plane, atlasX, atlasZ)
    end)
    validateLevel(level, "icons", "map_icons", function(plane, atlasX, atlasZ)
        return string.format("icon_%s_%s_%s.png", plane, atlasX, atlasZ)
    end)
end

local uniqueFiles = 0
for _ in pairs(referencedFiles) do uniqueFiles = uniqueFiles + 1 end
assert(logicalTiles > 0 and uniqueFiles > 0)

local discoveredFiles = 0
local files = assert(io.popen(
    "find resources/maps resources/map_icons -type f -name '*.png' -print", "r"))
for path in files:lines() do
    discoveredFiles = discoveredFiles + 1
    assert(referencedFiles[path], "unreferenced generated asset: " .. path)
end
assert(files:close(), "failed to enumerate generated assets")
assert(discoveredFiles == uniqueFiles,
    "the packaged PNG set must exactly match the generated manifest")

local manifest = assert(io.open("data/map_tiles.lua", "rb"))
local manifestText = assert(manifest:read("*a"))
manifest:close()
assert(manifestText:match("^%-%- Generated by tools/build_map_assets%.mjs; do not edit by hand%."),
    "the tile manifest must identify its generator and prohibit manual edits")
local previous
for plane, atlasX, atlasZ in manifestText:gmatch('%["(%d+):(%d+):(%d+)"%]') do
    local key = tonumber(plane) * 100000000 + tonumber(atlasX) * 10000 + tonumber(atlasZ)
    if previous and key < previous then
        -- Each level and icon section starts again at its first coordinate.
        assert(tonumber(plane) == 0, "manifest coordinates are not deterministic")
    end
    previous = key
end

print(string.format("asset manifest tests passed (%d logical tiles, %d files)",
    logicalTiles, uniqueFiles))
